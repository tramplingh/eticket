"""Admin reports. The per-event figures read from the views defined in sql/02_programmability.sql
(v_event_sales, v_event_availability), so the API and Workbench report the same numbers."""
from datetime import date

from fastapi import APIRouter, Depends, HTTPException, Query

from app.database import fetch_all, fetch_one, get_db
from app.deps import require_admin
from app.queries import load_bookings
from app.schemas import BookingOut, EventAvailabilityRow, PopularEvent, RevenueReport, SeatAvailability

# Every report is admin-only.
router = APIRouter(prefix="/reports", tags=["reports"], dependencies=[Depends(require_admin)])


@router.get("/revenue/{event_id}", response_model=RevenueReport)
async def event_revenue(event_id: int, db=Depends(get_db)):
    """Synopsis: calculate total revenue generated by an event (cancelled tickets excluded)."""
    row = await fetch_one(
        db,
        "SELECT event_id, event_name, revenue AS total_revenue, tickets_sold FROM v_event_sales WHERE event_id = %s",
        (event_id,),
    )
    if not row:
        raise HTTPException(status_code=404, detail="Event not found")
    return row


@router.get("/popular-events", response_model=list[PopularEvent])
async def popular_events(limit: int = Query(5, ge=1, le=50), db=Depends(get_db)):
    """Synopsis: find the most frequently booked events."""
    return await fetch_all(
        db,
        """
        SELECT e.event_id, e.event_name, COUNT(t.ticket_id) AS tickets_sold
        FROM event e
        JOIN event_seat es ON es.event_id = e.event_id
        JOIN ticket t      ON t.event_seat_id = es.event_seat_id
        WHERE t.ticket_status <> 'cancelled'
        GROUP BY e.event_id, e.event_name
        ORDER BY tickets_sold DESC, e.event_id
        LIMIT %s
        """,
        (limit,),
    )


@router.get("/seat-availability", response_model=list[EventAvailabilityRow])
async def seat_availability_all(db=Depends(get_db)):
    """Synopsis: find the number of available and booked seats, for every event at once."""
    return await fetch_all(
        db,
        """
        SELECT a.event_id, a.event_name, a.event_date, a.venue_name, a.city,
               a.seats_total, a.seats_available, a.seats_locked, a.seats_booked,
               s.tickets_sold, s.revenue
        FROM v_event_availability a
        JOIN v_event_sales s ON s.event_id = a.event_id
        ORDER BY a.event_date, a.event_time
        """,
    )


@router.get("/seat-availability/{event_id}", response_model=SeatAvailability)
async def seat_availability(event_id: int, db=Depends(get_db)):
    row = await fetch_one(
        db,
        "SELECT event_id, seats_total, seats_available AS available, seats_locked AS locked, "
        "seats_booked AS booked FROM v_event_availability WHERE event_id = %s",
        (event_id,),
    )
    if not row or not row["seats_total"]:
        raise HTTPException(status_code=404, detail="No seats found for this event")
    return row


@router.get("/bookings-by-date", response_model=list[BookingOut])
async def bookings_by_date(booking_date: date = Query(...), db=Depends(get_db)):
    """Synopsis: display all bookings for a particular date."""
    # Half-open range instead of DATE(booking_date) = ... so idx_booking_date stays usable.
    return await load_bookings(
        db,
        "b.booking_date >= %s AND b.booking_date < DATE_ADD(%s, INTERVAL 1 DAY)",
        (booking_date, booking_date),
    )
